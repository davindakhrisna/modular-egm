#!/usr/bin/env bash
set -euo pipefail

# ==============================================================================
# modular-egm — Non-Invasive Host Workspace Injector & Restorer
# ==============================================================================
# Appends and cleanly strips delimited EGM rule blocks in AGENTS.md / CLAUDE.md,
# registers modular-egm/ in .git/info/exclude, and generates ephemeral MCP and
# plugin configurations inside modular-egm/.workspace/.
# ==============================================================================

EGM_START_MARKER="<!-- >>> MODULAR-EGM-START (AUTO-GENERATED BY MODULAR-EGM - CLEANED ON EXIT) >>> -->"
EGM_END_MARKER="<!-- <<< MODULAR-EGM-END <<< -->"
GIT_EXCLUDE_START="# >>> MODULAR-EGM-EXCLUDE-START >>>"
GIT_EXCLUDE_END="# <<< MODULAR-EGM-EXCLUDE-END <<<"

CREATED_FILES=()
INJECTED_FILES=()
GIT_EXCLUDE_INJECTED=0
AGY_PLUGIN_BACKUP=""
AGY_PLUGIN_INSTALLED=0

strip_delimited_block() {
	local target_file="$1"
	local start_marker="$2"
	local end_marker="$3"

	if [[ ! -f "$target_file" ]]; then
		return 0
	fi

	local tmp_file
	tmp_file="$(mktemp)"
	awk -v start="$start_marker" -v end="$end_marker" '
    $0 == start { skip = 1; next }
    $0 == end   { skip = 0; next }
    !skip       { print }
  ' "$target_file" >"$tmp_file"

	cat "$tmp_file" >"$target_file"
	rm -f "$tmp_file"
}

egm_inject_git_exclude() {
	local host_root="$1"
	local egm_rel_dir="$2"
	local exclude_file="$host_root/.git/info/exclude"

	if [[ ! -d "$host_root/.git" ]]; then
		return 0
	fi

	mkdir -p "$host_root/.git/info"
	touch "$exclude_file"

	strip_delimited_block "$exclude_file" "$GIT_EXCLUDE_START" "$GIT_EXCLUDE_END"

	{
		printf '%s\n' "$GIT_EXCLUDE_START"
		printf '/%s/\n' "$egm_rel_dir"
		printf '/AGENTS.md\n'
		printf '/CLAUDE.md\n'
		printf '%s\n' "$GIT_EXCLUDE_END"
	} >>"$exclude_file"

	GIT_EXCLUDE_INJECTED=1
}

egm_append_rule_file() {
	local target_file="$1"
	local rendered_block_file="$2"

	if [[ -f "$target_file" ]]; then
		strip_delimited_block "$target_file" "$EGM_START_MARKER" "$EGM_END_MARKER"
		printf '\n' >>"$target_file"
		cat "$rendered_block_file" >>"$target_file"
		INJECTED_FILES+=("$target_file")
	else
		cat "$rendered_block_file" >"$target_file"
		CREATED_FILES+=("$target_file")
	fi
}

egm_prepare_workspace() {
	local host_root="$1"
	local egm_root="$2"
	local harness_name="$3"
	local orchestrator_model="$4"
	local worker_model="$5"

	local workspace_dir="$egm_root/.workspace"
	mkdir -p "$workspace_dir/designs" "$workspace_dir/playwright" "$workspace_dir/scratch"

	# Render the injected EGM rulebook block with active harness & model tiers
	local rendered_block="$workspace_dir/rendered-egm-block.md"
	sed \
		-e "s/__EGM_HARNESS_NAME__/$harness_name/g" \
		-e "s/__EGM_ORCHESTRATOR_MODEL__/$orchestrator_model/g" \
		-e "s/__EGM_WORKER_MODEL__/$worker_model/g" \
		"$egm_root/rules/egm-injected-block.md" >"$rendered_block"

	# Render MCP config pointing to egm-playwright-mcp
	local mcp_wrapper="$egm_root/scripts/playwright-mcp-wrapper.sh"
	cat >"$workspace_dir/mcp.json" <<EOF
{
  "mcpServers": {
    "playwright": {
      "command": "$mcp_wrapper",
      "args": [],
      "env": {
        "EGM_PLAYWRIGHT_DIR": "$workspace_dir/playwright"
      }
    }
  }
}
EOF

	# Exclude modular-egm from host git status
	local egm_rel_dir
	egm_rel_dir="$(basename "$egm_root")"
	egm_inject_git_exclude "$host_root" "$egm_rel_dir"

	# Inject or create AGENTS.md (used by Codex & Antigravity)
	egm_append_rule_file "$host_root/AGENTS.md" "$rendered_block"

	# Inject or create CLAUDE.md when launching Claude Code (or if CLAUDE.md already exists)
	if [[ "$harness_name" == "Claude Code" || -f "$host_root/CLAUDE.md" ]]; then
		egm_append_rule_file "$host_root/CLAUDE.md" "$rendered_block"
	fi
}

egm_install_agy_plugin() {
	local egm_root="$1"
	local agy_plugin_dir="${HOME}/.gemini/config/plugins/egm"

	mkdir -p "${HOME}/.gemini/config/plugins"
	if [[ -e "$agy_plugin_dir" || -L "$agy_plugin_dir" ]]; then
		AGY_PLUGIN_BACKUP="${agy_plugin_dir}.backup.$$"
		mv "$agy_plugin_dir" "$AGY_PLUGIN_BACKUP"
	fi

	ln -s "$egm_root" "$agy_plugin_dir"
	AGY_PLUGIN_INSTALLED=1
}

egm_cleanup_workspace() {
	local host_root="$1"

	# 1. Remove any files created purely by modular-egm
	local created
	for created in "${CREATED_FILES[@]}"; do
		if [[ -f "$created" ]]; then
			rm -f "$created"
		fi
	done

	# 2. Strip appended blocks from pre-existing host rule files
	local injected
	for injected in "${INJECTED_FILES[@]}"; do
		if [[ -f "$injected" ]]; then
			strip_delimited_block "$injected" "$EGM_START_MARKER" "$EGM_END_MARKER"
			# Remove trailing blank line added before block
			sed -i -e :a -e '/^\n*$/{$d;N;ba' -e '}' "$injected" 2>/dev/null || true
		fi
	done

	# 3. Restore Antigravity plugin directory if modified
	local agy_plugin_dir="${HOME}/.gemini/config/plugins/egm"
	if [[ "$AGY_PLUGIN_INSTALLED" -eq 1 ]]; then
		rm -f "$agy_plugin_dir"
		if [[ -n "$AGY_PLUGIN_BACKUP" && -e "$AGY_PLUGIN_BACKUP" ]]; then
			mv "$AGY_PLUGIN_BACKUP" "$agy_plugin_dir"
		fi
	fi

	# 4. Keep modular-egm/ excluded in .git/info/exclude while removing AGENTS.md/CLAUDE.md exclude lines
	if [[ "$GIT_EXCLUDE_INJECTED" -eq 1 && -f "$host_root/.git/info/exclude" ]]; then
		local egm_rel_dir
		egm_rel_dir="$(basename "$EGM_ROOT")"
		strip_delimited_block "$host_root/.git/info/exclude" "$GIT_EXCLUDE_START" "$GIT_EXCLUDE_END"
		{
			printf '%s\n' "$GIT_EXCLUDE_START"
			printf '/%s/\n' "$egm_rel_dir"
			printf '%s\n' "$GIT_EXCLUDE_END"
		} >>"$host_root/.git/info/exclude"
	fi
}
